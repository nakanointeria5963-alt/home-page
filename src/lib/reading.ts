/**
 * 読み上げ用の文に直す。
 * 長い言葉から先に置き換える。そうしないと「9月14日」が
 * 「14日」に先に食われて、読みが崩れる。
 */
const SORTED = [...READING_DICTIONARY].sort((a, b) => b[0].length - a[0].length);

export function toSpeech(text: string): string {
  let out = text;
  for (const [word, reading] of SORTED) out = out.split(word).join(reading);
  // 「分」は「ふん」とも「ぶん」とも読む。分けるのは、直前の1文字。
  //   ・数字や漢字のあと → そのままでいい(3分=ふん / 自分・気分・部分=ぶん)
  //   ・ひらがなのあと   → ほぼ「ぶん」(作ってあった分、その分、言い分)
  // ただし「分かる」「分ける」だけは「わ」なので、次が「か」「け」なら触らない。
  // ノブさんの指摘(2026-08-29):「それまでに作ってあった分」が「ふん」だった
  out = out.replace(/([ぁ-ん])分(?![かけ])/g, "$1ぶん");

  // 「方」も「ほう」と「かた」がある。分けるのは、やはり直前の1文字。
  //   ・「た」「だ」のあと → ほう(使った方がいい、やめた方がいい)
  //   ・それ以外          → そのまま(作り方・使い方・考え方=かた / 方法・方向=ほう)
  // 「した方法」のように、うしろが熟語のときは手を出さない。
  // ノブさんの指摘(2026-08-29):「お金を使った方が」が「かた」だった
  out = out.replace(/([ただ])方(?![法向面角程式針位])/g, "$1ほう");

  // 記号は声にならない。読点に変えて「間」にする。
  // そのままだと「——」を無視して詰めて読んでしまう
  out = out.replace(/[—―−–]{1,}|[…]{1,}|\.{3,}/g, "、");
  // かぎかっこは読まないほうが自然に聞こえる
  out = out.replace(/[「」『』]/g, " ");
  return out;
}

